"""
NourFi — Embedding Verification
================================

Verifies the embeddings generated by:

    app/rag/embeddings.py

Run from repository root:

    python scripts/verify_embeddings.py
"""

import json
from pathlib import Path

import numpy as np


# ============================================================
# Paths
# ============================================================

BASE_DIR = Path(__file__).resolve().parents[1]

VECTOR_PATH = (
    BASE_DIR
    / "data"
    / "processed"
    / "aaoifi_embeddings.npz"
)

METADATA_PATH = (
    BASE_DIR
    / "data"
    / "processed"
    / "aaoifi_embedding_metadata.json"
)

CHUNKS_PATH = (
    BASE_DIR
    / "data"
    / "processed"
    / "aaoifi_rag_chunks_500.json"
)


# ============================================================
# Helpers
# ============================================================

def fail(message):

    raise RuntimeError(
        f"[✗] {message}"
    )


def check(condition, message):

    if not condition:

        fail(message)

    print(
        f"[✓] {message}"
    )


# ============================================================
# Main verification
# ============================================================

def main():

    print("=" * 70)

    print(
        "NOURFI — EMBEDDING VERIFICATION"
    )

    print("=" * 70)

    print()

    # --------------------------------------------------------
    # 1. Check files
    # --------------------------------------------------------

    print(
        "[1] Checking files..."
    )

    check(
        VECTOR_PATH.exists(),
        f"Vector file exists: {VECTOR_PATH.name}"
    )

    check(
        METADATA_PATH.exists(),
        f"Metadata file exists: {METADATA_PATH.name}"
    )

    check(
        CHUNKS_PATH.exists(),
        f"Chunk file exists: {CHUNKS_PATH.name}"
    )

    print()

    # --------------------------------------------------------
    # 2. Load vectors
    # --------------------------------------------------------

    print(
        "[2] Loading vectors..."
    )

    data = np.load(
        VECTOR_PATH
    )

    check(
        "embeddings" in data,
        "Embeddings array exists."
    )

    embeddings = data[
        "embeddings"
    ]

    print(
        f"    Shape: {embeddings.shape}"
    )

    check(
        embeddings.ndim == 2,
        "Embeddings are a 2D matrix."
    )

    num_vectors = embeddings.shape[0]

    dimension = embeddings.shape[1]

    check(
        num_vectors > 0,
        "At least one embedding exists."
    )

    check(
        dimension > 0,
        "Embedding dimension is valid."
    )

    print()

    # --------------------------------------------------------
    # 3. Check numerical validity
    # --------------------------------------------------------

    print(
        "[3] Checking numerical values..."
    )

    check(
        np.isfinite(embeddings).all(),
        "No NaN or infinite values found."
    )

    check(
        embeddings.dtype
        in (
            np.float32,
            np.float64
        ),
        f"Embedding dtype is numeric: {embeddings.dtype}"
    )

    print()

    # --------------------------------------------------------
    # 4. Check normalization
    # --------------------------------------------------------

    print(
        "[4] Checking vector normalization..."
    )

    norms = np.linalg.norm(
        embeddings,
        axis=1
    )

    min_norm = float(
        norms.min()
    )

    max_norm = float(
        norms.max()
    )

    mean_norm = float(
        norms.mean()
    )

    print(
        f"    Min norm : {min_norm:.6f}"
    )

    print(
        f"    Max norm : {max_norm:.6f}"
    )

    print(
        f"    Mean norm: {mean_norm:.6f}"
    )

    check(
        np.allclose(
            norms,
            1.0,
            atol=1e-4
        ),
        "All embeddings are normalized to unit length."
    )

    print()

    # --------------------------------------------------------
    # 5. Load metadata
    # --------------------------------------------------------

    print(
        "[5] Loading metadata..."
    )

    with open(
        METADATA_PATH,
        "r",
        encoding="utf-8"
    ) as f:

        metadata_data = json.load(f)

    metadata = metadata_data.get(
        "metadata",
        []
    )

    check(
        len(metadata) > 0,
        "Embedding metadata is not empty."
    )

    check(
        len(metadata)
        == num_vectors,
        (
            "Number of metadata records "
            "matches number of vectors."
        )
    )

    print()

    # --------------------------------------------------------
    # 6. Check indexes
    # --------------------------------------------------------

    print(
        "[6] Checking embedding indexes..."
    )

    indexes = [
        item.get(
            "embedding_index"
        )
        for item in metadata
    ]

    expected_indexes = list(
        range(num_vectors)
    )

    check(
        indexes == expected_indexes,
        "Embedding indexes are sequential and correctly ordered."
    )

    print()

    # --------------------------------------------------------
    # 7. Check chunk IDs
    # --------------------------------------------------------

    print(
        "[7] Checking chunk IDs..."
    )

    chunk_ids = [
        item.get("chunk_id")
        for item in metadata
    ]

    check(
        all(
            chunk_id
            for chunk_id in chunk_ids
        ),
        "Every embedding has a chunk_id."
    )

    check(
        len(chunk_ids)
        == len(set(chunk_ids)),
        "All chunk IDs are unique."
    )

    print()

    # --------------------------------------------------------
    # 8. Compare against original chunks
    # --------------------------------------------------------

    print(
        "[8] Comparing with processed chunks..."
    )

    with open(
        CHUNKS_PATH,
        "r",
        encoding="utf-8"
    ) as f:

        chunks_data = json.load(f)

    chunks = chunks_data.get(
        "chunks",
        []
    )

    check(
        len(chunks)
        == num_vectors,
        (
            "Number of original chunks "
            "matches number of embeddings."
        )
    )

    original_ids = [
        chunk.get("chunk_id")
        for chunk in chunks
    ]

    check(
        original_ids == chunk_ids,
        (
            "Embedding metadata follows "
            "the exact same chunk order."
        )
    )

    # --------------------------------------------------------
    # 9. Compare texts
    # --------------------------------------------------------

    print()

    print(
        "[9] Checking text alignment..."
    )

    for i, chunk in enumerate(chunks):

        metadata_text = metadata[i].get(
            "text",
            ""
        )

        chunk_text = chunk.get(
            "text",
            ""
        )

        if metadata_text != chunk_text:

            fail(
                f"Text mismatch at embedding "
                f"index {i} "
                f"({chunk.get('chunk_id')})"
            )

    print(
        "[✓] All embedding texts match the original chunks."
    )

    # --------------------------------------------------------
    # 10. Check model information
    # --------------------------------------------------------

    print()

    print(
        "[10] Checking model information..."
    )

    model_name = metadata_data.get(
        "embedding_model"
    )

    check(
        bool(model_name),
        f"Embedding model recorded: {model_name}"
    )

    recorded_dimension = metadata_data.get(
        "embedding_dimension"
    )

    check(
        recorded_dimension == dimension,
        (
            "Recorded embedding dimension "
            "matches actual dimension."
        )
    )

    print()

    # --------------------------------------------------------
    # 11. Sample vectors
    # --------------------------------------------------------

    print(
        "[11] Sample vectors..."
    )

    sample_count = min(
        3,
        num_vectors
    )

    for i in range(sample_count):

        chunk_id = metadata[i][
            "chunk_id"
        ]

        vector = embeddings[i]

        print()

        print(
            f"    {chunk_id}"
        )

        print(
            "    First 5 values:"
        )

        print(
            "    ",
            vector[:5]
        )

    # --------------------------------------------------------
    # 12. Final result
    # --------------------------------------------------------

    print()

    print("=" * 70)

    print(
        "EMBEDDING VERIFICATION PASSED"
    )

    print("=" * 70)

    print(
        f"[✓] Vectors       : {num_vectors}"
    )

    print(
        f"[✓] Dimension     : {dimension}"
    )

    print(
        f"[✓] Model         : {model_name}"
    )

    print(
        f"[✓] Normalized    : "
        f"{metadata_data.get('normalization')}"
    )

    print(
        "[✓] Metadata      : aligned"
    )

    print(
        "[✓] Chunk IDs     : unique"
    )

    print(
        "[✓] Text mapping  : correct"
    )

    print()
    print(
        "Next step:"
    )

    print(
        "    Build the vector store / similarity search."
    )


if __name__ == "__main__":
    main()